/**
 * Track 2 Evaluation Harness
 *
 * Baseline vs. Trajectory Accuracy Comparison Script
 *
 * Usage:
 *   npx tsx eval/run-eval.ts [--dataset <path>] [--output <path>] [--ablation <flags>]
 *
 * This script:
 * 1. Loads a labeled dataset of photo observations (with ground-truth stage labels)
 * 2. Runs the per-image baseline classifier (no graph constraints) on each element
 * 3. Runs the Viterbi trajectory fitter (with graph constraints + observability) on each element
 * 4. Computes accuracy, false-alert rate, confusion matrix for both
 * 5. Runs ablation variants (disabling graph constraints / observability awareness)
 * 6. Writes a reproducible JSON + Markdown report to eval/reports/
 * 7. Updates EVIDENCE.md with the run summary
 *
 * IMPORTANT: Results in EVIDENCE.md must come from actual eval runs against
 * real or realistic data. Do not fabricate numbers. Empty sections are better
 * than invented ones.
 */

