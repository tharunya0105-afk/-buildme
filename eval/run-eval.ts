// ─── Dataset Types ─────────────────────────────────────────────────────────────

/**
 * Ground-truth label for a single structural element's stage at a point in time.
 * Must be assigned by a human with on-site knowledge — not generated by the model.
 */
export interface GroundTruthLabel {
  elementId: string;
  elementType: string;
  labelDate: string;             // ISO date when label was assigned
  trueStageId: string;           // ground-truth stage at labelDate
  labelSource: "engineer_onsite" | "document" | "photo_review"; // how was it verified?
  labelledBy: string;            // non-PII ref, e.g. "Engineer A"
  notes?: string;
}

/**
 * A dataset entry: one element with its time-series observations and ground truth.
 */
export interface DatasetEntry {
  elementId: string;
  elementType: string;
  projectRef: string;   // non-PII project reference (e.g. "Project-001")
  observations: StageObservation[];
  groundTruth: GroundTruthLabel[];
}

export interface EvalDataset {
  version: string;
  createdAt: string;
  description: string;
  licenseNote: string;  // must verify license before use
  entries: DatasetEntry[];
}

// ─── Metrics ──────────────────────────────────────────────────────────────────

export interface ElementMetrics {
  elementId: string;
  elementType: string;
  projectRef: string;
  observationCount: number;
  groundTruthCount: number;

  // Trajectory method
  trajectoryFinalStage: string | null;
  trajectoryAbstained: boolean;
  trajectoryConfidence: number;
  trajectoryCorrect: boolean | null;  // null if abstained

  // Baseline method (per-image argmax, no graph constraints)
  baselineFinalStage: string | null;
  baselineCorrect: boolean | null;

  // Stage-level comparison (if multiple ground truth points)
  trajectoryAccuracyByStage: Record<string, boolean | null>;
  baselineAccuracyByStage: Record<string, boolean | null>;
}

export interface AblationConfig {
  name: string;
  description: string;
  config: TrajectoryConfig;
}

export interface AblationResult {
  name: string;
  description: string;
  config: TrajectoryConfig;
  accuracy: number;
  abstentionRate: number;
  falseAlertRate: number;
}

export interface EvalReport {
  runId: string;
  runAt: string;
  datasetVersion: string;
  datasetSize: number;
  totalElements: number;

  // Primary metrics
  trajectoryAccuracy: number;       // % correct among non-abstained
  baselineAccuracy: number;         // % correct for per-image baseline
  accuracyImprovement: number;      // trajectory - baseline (positive = better)

  abstentionRate: number;           // % elements where system abstained
  falseAlertRate: number;           // % abstentions that were actually correct (false alarm)

  // Per-element details
  elementMetrics: ElementMetrics[];

  // Ablation results
  ablationResults: AblationResult[];

  // Robustness results (degraded input tests)
  robustnessResults: RobustnessResult[];

  // Confusion matrix (trajectory)
  confusionMatrix: ConfusionMatrix;

  // Config used
  configUsed: TrajectoryConfig;
}

export interface RobustnessResult {
  degradationType: "blur" | "missing_frames" | "out_of_order" | "low_confidence";
  description: string;
  trajectoryAccuracy: number;
  baselineAccuracy: number;
  abstentionRate: number;
}

export interface ConfusionMatrix {
  labels: string[];
  matrix: number[][];  // matrix[i][j] = count of true=i, predicted=j
}

// ─── Core Eval Logic ──────────────────────────────────────────────────────────

export function computeBaselineStage(observations: StageObservation[]): string | null {
  // Baseline: vote for the most frequent argmax across all photos
  const votes: Record<string, number> = {};
  for (const obs of observations) {
    let bestStage = "";
    let bestProb = -1;
    for (const [stageId, prob] of Object.entries(obs.stageProbabilities)) {
      if (prob > bestProb) {
        bestProb = prob;
        bestStage = stageId;
      }
    }
    if (bestStage) votes[bestStage] = (votes[bestStage] ?? 0) + 1;
  }
  return Object.entries(votes).sort(([, a], [, b]) => b - a)[0]?.[0] ?? null;
}

export function evalElement(
  entry: DatasetEntry,
  config: TrajectoryConfig
): ElementMetrics {
  const result = fitTrajectory(entry.elementType, entry.elementId, entry.observations, config);
  const baselineStage = computeBaselineStage(entry.observations);

  // Match ground truth by the latest label date
  const latestLabel = [...entry.groundTruth].sort(
    (a, b) => new Date(b.labelDate).getTime() - new Date(a.labelDate).getTime()
  )[0];

  const trueStage = latestLabel?.trueStageId ?? null;

  const trajectoryCorrect =
    result.abstained || !trueStage
      ? null
      : result.currentStage?.stageId === trueStage;
  const baselineCorrect =
    !baselineStage || !trueStage
      ? null
      : baselineStage === trueStage;

  // Per-stage accuracy (for elements with multiple ground truth points)
  const trajectoryAccuracyByStage: Record<string, boolean | null> = {};
  const baselineAccuracyByStage: Record<string, boolean | null> = {};

  for (const label of entry.groundTruth) {
    const fittedStage = result.fittedPath.find((s) => s.stageId === label.trueStageId);
    trajectoryAccuracyByStage[label.trueStageId] =
      fittedStage ? fittedStage.status !== "unsupported" : false;
    baselineAccuracyByStage[label.trueStageId] = baselineStage === label.trueStageId;
  }

  return {
    elementId: entry.elementId,
    elementType: entry.elementType,
    projectRef: entry.projectRef,
    observationCount: entry.observations.length,
    groundTruthCount: entry.groundTruth.length,
    trajectoryFinalStage: result.currentStage?.stageId ?? null,
    trajectoryAbstained: result.abstained,
    trajectoryConfidence: result.trajectoryConfidence,
    trajectoryCorrect,
    baselineFinalStage: baselineStage,
    baselineCorrect,
    trajectoryAccuracyByStage,
    baselineAccuracyByStage,
  };
}

export function computeAggregateMetrics(
  metrics: ElementMetrics[]
): Omit<EvalReport, "runId" | "runAt" | "datasetVersion" | "datasetSize" | "totalElements" | "elementMetrics" | "ablationResults" | "robustnessResults" | "confusionMatrix" | "configUsed"> {
  const nonAbstained = metrics.filter((m) => !m.trajectoryAbstained && m.trajectoryCorrect !== null);
  const abstained = metrics.filter((m) => m.trajectoryAbstained);

  const trajectoryCorrect = nonAbstained.filter((m) => m.trajectoryCorrect === true).length;
  const trajectoryAccuracy = nonAbstained.length > 0 ? trajectoryCorrect / nonAbstained.length : 0;

  const baselineValid = metrics.filter((m) => m.baselineCorrect !== null);
  const baselineCorrect = baselineValid.filter((m) => m.baselineCorrect === true).length;
  const baselineAccuracy = baselineValid.length > 0 ? baselineCorrect / baselineValid.length : 0;

  const abstentionRate = metrics.length > 0 ? abstained.length / metrics.length : 0;

  // False alert rate: abstentions where trajectory WOULD have been correct
  // (i.e., the engine abstained unnecessarily)
  // This requires running without abstention threshold to know what the answer would be
  const falseAlertRate = 0; // TODO: compute in second pass without abstention threshold

  return {
    trajectoryAccuracy,
    baselineAccuracy,
    accuracyImprovement: trajectoryAccuracy - baselineAccuracy,
    abstentionRate,
    falseAlertRate,
  };
}

// ─── Ablation Runs ─────────────────────────────────────────────────────────────

const ABLATION_CONFIGS: AblationConfig[] = [
  {
    name: "full_system",
    description: "Full system: graph constraints + observability + abstention",
    config: DEFAULT_TRAJECTORY_CONFIG,
  },
  {
    name: "no_observability",
    description: "Ablation: disable observability-awareness (no inferred_concealed labels)",
    config: { ...DEFAULT_TRAJECTORY_CONFIG, observabilityAware: false },
  },
  {
    name: "no_graph",
    description: "Ablation: disable graph constraints (any stage-to-stage transition allowed)",
    config: { ...DEFAULT_TRAJECTORY_CONFIG, graphConstrained: false },
  },
  {
    name: "no_abstention",
    description: "Ablation: disable abstention (always emit a result)",
    config: { ...DEFAULT_TRAJECTORY_CONFIG, abstentionThreshold: 0 },
  },
  {
    name: "baseline",
    description: "Baseline: per-image argmax only (no trajectory, no constraints)",
    config: { ...DEFAULT_TRAJECTORY_CONFIG, graphConstrained: false, observabilityAware: false, abstentionThreshold: 0 },
  },
];

// ─── Robustness Tests ──────────────────────────────────────────────────────────

function degradeObservations(
  observations: StageObservation[],
  type: RobustnessResult["degradationType"]
): StageObservation[] {
  switch (type) {
    case "blur":
      // Simulate blur: halve all probabilities (uncertain classifier)
      return observations.map((o) => ({
        ...o,
        overallConfidence: (o.overallConfidence ?? 0.5) * 0.5,
        stageProbabilities: Object.fromEntries(
          Object.entries(o.stageProbabilities).map(([k, v]) => [k, v * 0.5])
        ),
      }));

    case "missing_frames":
      // Remove 50% of observations (simulating upload failures)
      return observations.filter((_, i) => i % 2 === 0);

    case "out_of_order":
      // Shuffle timestamps
      const shuffled = [...observations];
      for (let i = shuffled.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
      }
      return shuffled;

    case "low_confidence":
      // All observations have very low confidence
      return observations.map((o) => ({
        ...o,
        overallConfidence: 0.2,
        stageProbabilities: Object.fromEntries(
          Object.entries(o.stageProbabilities).map(([k, v]) => [k, v * 0.3])
        ),
      }));
  }
}

// ─── Report Writer ─────────────────────────────────────────────────────────────

function writeMarkdownReport(report: EvalReport, outputDir: string): string {
  const pct = (v: number) => `${(v * 100).toFixed(1)}%`;
  const md = `# BuildMe Track 2 — Evaluation Report

**Run ID**: \`${report.runId}\`
**Run At**: ${report.runAt}
**Dataset**: v${report.datasetVersion} — ${report.datasetSize} photos across ${report.totalElements} elements

---

## Primary Results

| Metric | Trajectory System | Baseline (Per-Image) |
|--------|------------------|---------------------|
| Accuracy (non-abstained) | **${pct(report.trajectoryAccuracy)}** | ${pct(report.baselineAccuracy)} |
| Accuracy improvement | **+${pct(report.accuracyImprovement)}** | — |
| Abstention rate | ${pct(report.abstentionRate)} | 0% (never abstains) |
| False alert rate | ${pct(report.falseAlertRate)} | — |

> **Note**: Accuracy is measured on elements where the system did NOT abstain. The baseline never
> abstains and so is evaluated on all elements, which inflates its denominator.

---

## Ablation Table

| Configuration | Accuracy | Abstention Rate | False Alert Rate |
|---------------|----------|-----------------|-----------------|
${report.ablationResults.map((a) => `| ${a.name} | ${pct(a.accuracy)} | ${pct(a.abstentionRate)} | ${pct(a.falseAlertRate)} |`).join("\n")}

---

## Robustness Results

| Degradation | Trajectory Accuracy | Baseline Accuracy | Abstention Rate |
|-------------|--------------------|--------------------|-----------------|
${report.robustnessResults.map((r) => `| ${r.degradationType} | ${pct(r.trajectoryAccuracy)} | ${pct(r.baselineAccuracy)} | ${pct(r.abstentionRate)} |`).join("\n")}

---

## Per-Element Detail

| Element | Type | Project | Obs | GT | Traj Stage | Traj Correct | Baseline Stage | Baseline Correct |
|---------|------|---------|-----|----|-----------|----|-------------|-----|
${report.elementMetrics
  .map(
    (m) =>
      `| ${m.elementId.slice(0, 8)} | ${m.elementType} | ${m.projectRef} | ${m.observationCount} | ${m.groundTruthCount} | ${m.trajectoryFinalStage ?? "—"} | ${m.trajectoryAbstained ? "abstained" : m.trajectoryCorrect === null ? "—" : m.trajectoryCorrect ? "✓" : "✗"} | ${m.baselineFinalStage ?? "—"} | ${m.baselineCorrect === null ? "—" : m.baselineCorrect ? "✓" : "✗"} |`
  )
  .join("\n")}

---

*Generated by BuildMe eval harness — do not manually edit accuracy numbers.*
*All values must come from actual eval runs against real or realistic data.*
`;

  const filename = `report-${report.runId}.md`;
  const filepath = path.join(outputDir, filename);
  fs.mkdirSync(outputDir, { recursive: true });
  fs.writeFileSync(filepath, md, "utf8");
  fs.writeFileSync(path.join(outputDir, `report-${report.runId}.json`), JSON.stringify(report, null, 2), "utf8");
  return filepath;
}

function updateEvidenceMd(report: EvalReport, evidencePath: string): void {
  const pct = (v: number) => `${(v * 100).toFixed(1)}%`;
  const entry = `
### Eval Run: ${report.runId}
- **Date**: ${report.runAt}
- **Dataset**: v${report.datasetVersion} — ${report.totalElements} elements, ${report.datasetSize} photos
- **Trajectory Accuracy**: ${pct(report.trajectoryAccuracy)} vs Baseline ${pct(report.baselineAccuracy)} (+${pct(report.accuracyImprovement)})
- **Abstention Rate**: ${pct(report.abstentionRate)}
- **Report**: \`eval/reports/report-${report.runId}.md\`
`;

  let existing = "";
  try { existing = fs.readFileSync(evidencePath, "utf8"); } catch { existing = "# EVIDENCE.md\n\n## Eval Runs\n"; }
  const updated = existing.includes("## Eval Runs")
    ? existing.replace("## Eval Runs", `## Eval Runs${entry}`)
    : existing + entry;
  fs.writeFileSync(evidencePath, updated, "utf8");
}

// ─── Main ──────────────────────────────────────────────────────────────────────

export async function runEval(
  datasetPath: string,
  outputDir = "eval/reports",
  evidencePath = "EVIDENCE.md"
): Promise<EvalReport> {
  console.log(`[eval] Loading dataset from ${datasetPath}…`);
  const raw = fs.readFileSync(datasetPath, "utf8");
  const dataset: EvalDataset = JSON.parse(raw);

  console.log(`[eval] Dataset: v${dataset.version} — ${dataset.entries.length} elements`);
  console.log(`[eval] License note: ${dataset.licenseNote}`);

  // Primary eval
  const elementMetrics = dataset.entries.map((entry) =>
    evalElement(entry, DEFAULT_TRAJECTORY_CONFIG)
  );

  const {
    trajectoryAccuracy,
    baselineAccuracy,
    accuracyImprovement,
    abstentionRate,
    falseAlertRate,
  } = computeAggregateMetrics(elementMetrics);

  console.log(`[eval] Trajectory accuracy: ${(trajectoryAccuracy * 100).toFixed(1)}%`);
  console.log(`[eval] Baseline accuracy:   ${(baselineAccuracy * 100).toFixed(1)}%`);
  console.log(`[eval] Improvement:         +${(accuracyImprovement * 100).toFixed(1)}%`);
  console.log(`[eval] Abstention rate:     ${(abstentionRate * 100).toFixed(1)}%`);

  // Ablation runs
  console.log("[eval] Running ablations…");
  const ablationResults: AblationResult[] = ABLATION_CONFIGS.map((abl) => {
    const metrics = dataset.entries.map((entry) => evalElement(entry, abl.config));
    const agg = computeAggregateMetrics(metrics);
    return {
      name: abl.name,
      description: abl.description,
      config: abl.config,
      accuracy: agg.trajectoryAccuracy,
      abstentionRate: agg.abstentionRate,
      falseAlertRate: agg.falseAlertRate,
    };
  });

  // Robustness tests
  console.log("[eval] Running robustness tests…");
  const degradationTypes: RobustnessResult["degradationType"][] = [
    "blur",
    "missing_frames",
    "out_of_order",
    "low_confidence",
  ];

  const robustnessResults: RobustnessResult[] = degradationTypes.map((dtype) => {
    const degradedEntries = dataset.entries.map((entry) => ({
      ...entry,
      observations: degradeObservations(entry.observations, dtype),
    }));
    const metrics = degradedEntries.map((entry) => evalElement(entry, DEFAULT_TRAJECTORY_CONFIG));
    const agg = computeAggregateMetrics(metrics);
    const baselineMetrics = degradedEntries.map((entry) => {
      const baselineStage = computeBaselineStage(entry.observations);
      const trueStage = [...entry.groundTruth].sort(
        (a, b) => new Date(b.labelDate).getTime() - new Date(a.labelDate).getTime()
      )[0]?.trueStageId;
      return { correct: baselineStage === trueStage };
    });
    const baselineAcc = baselineMetrics.filter((m) => m.correct).length / Math.max(baselineMetrics.length, 1);

    return {
      degradationType: dtype,
      description: `Input degradation: ${dtype}`,
      trajectoryAccuracy: agg.trajectoryAccuracy,
      baselineAccuracy: baselineAcc,
      abstentionRate: agg.abstentionRate,
    };
  });

  // Build confusion matrix
  const allStageIds = [...new Set([
    ...elementMetrics.map((m) => m.trajectoryFinalStage).filter(Boolean) as string[],
    ...elementMetrics.flatMap((m) => Object.keys(m.trajectoryAccuracyByStage)),
  ])];
  const cMatrix: number[][] = allStageIds.map(() => allStageIds.map(() => 0));
  for (const m of elementMetrics) {
    if (m.trajectoryFinalStage && !m.trajectoryAbstained) {
      const trueStage = Object.keys(m.trajectoryAccuracyByStage)[0];
      const predIdx = allStageIds.indexOf(m.trajectoryFinalStage);
      const trueIdx = allStageIds.indexOf(trueStage);
      if (predIdx >= 0 && trueIdx >= 0) cMatrix[trueIdx][predIdx]++;
    }
  }

  const totalPhotos = dataset.entries.reduce((s, e) => s + e.observations.length, 0);

  const report: EvalReport = {
    runId: `eval-${Date.now()}`,
    runAt: new Date().toISOString(),
    datasetVersion: dataset.version,
    datasetSize: totalPhotos,
    totalElements: dataset.entries.length,
    trajectoryAccuracy,
    baselineAccuracy,
    accuracyImprovement,
    abstentionRate,
    falseAlertRate,
    elementMetrics,
    ablationResults,
    robustnessResults,
    confusionMatrix: { labels: allStageIds, matrix: cMatrix },
    configUsed: DEFAULT_TRAJECTORY_CONFIG,
  };

  const reportPath = writeMarkdownReport(report, outputDir);
  updateEvidenceMd(report, evidencePath);

  console.log(`[eval] Report written to: ${reportPath}`);
  console.log("[eval] EVIDENCE.md updated");

  return report;
}

// CLI entry point
if (require.main === module) {
  const args = process.argv.slice(2);
  const datasetIdx = args.indexOf("--dataset");
  const datasetPath = datasetIdx >= 0 ? args[datasetIdx + 1] : "eval/sample-dataset.json";
  const outputIdx = args.indexOf("--output");
  const outputDir = outputIdx >= 0 ? args[outputIdx + 1] : "eval/reports";

  runEval(datasetPath, outputDir, "EVIDENCE.md").then(() => {
    console.log("[eval] Complete.");
  }).catch((err) => {
    console.error("[eval] Failed:", err);
    process.exit(1);
  });
}
